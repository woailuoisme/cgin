-- 默认与公共基础设施服务数据库模式定义
-- 包含基于 PostgreSQL 18 原生特性的单调递增 UUIDv7 生成函数、通用多态媒体资源附件表 (media) 以及通用站内通知系统表 (notifications)

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. 通用多态媒体资源附件表 (media，对齐 Spatie 规范)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE media (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 自增物理主键
  uuid varchar(36) NOT NULL DEFAULT uuidv7()::text, -- 对外暴露的 UUIDv7 安全唯一标识符（默认自动生成）
  model_type varchar(255) NOT NULL, -- 关联宿主业务模型类型（如 user, post）
  model_id varchar(255) NOT NULL, -- 关联宿主业务模型主键 ID
  collection_name varchar(255) NOT NULL, -- 媒体集合归类（如 avatar, document, gallery）
  disk varchar(255) NOT NULL, -- 存储驱动磁盘标识（如 local, s3）
  name varchar(255) NOT NULL, -- 媒体文件原始友好名称
  file_name varchar(255) NOT NULL, -- 存储端物理存储文件名
  mime_type varchar(255) NOT NULL, -- 媒体文件 MIME 类型（如 image/jpeg, application/pdf）
  conversions_disk varchar(255) NULL, -- 衍生版本与转码附件存储磁盘（为空时自动回退使用 disk）
  size bigint NOT NULL DEFAULT 0, -- 媒体文件尺寸大小（字节单位）
  conversion_status varchar(50) NOT NULL DEFAULT 'completed', -- 图片衍生版本或视频转码状态
  order_column integer NULL, -- 多附件排序列号
  manipulations jsonb NULL, -- 图片处理指令与参数元数据（JSONB）
  custom_properties jsonb NULL, -- 自定义扩展业务属性（JSONB）
  generated_conversions jsonb NOT NULL DEFAULT '{}'::jsonb, -- 已成功生成的转码衍生版本清单（JSONB）
  responsive_images jsonb NULL, -- 响应式多分辨率图片变体元数据（JSONB）
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 记录创建时间戳
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 记录最后更新时间戳
  PRIMARY KEY (id)
);

-- 媒体资源检索索引与唯一性约束
CREATE UNIQUE INDEX idx_media_uuid ON media (uuid); -- 对外安全 UUID 唯一索引
CREATE INDEX idx_media_model ON media (model_type, model_id); -- 多态关联复合索引，加速宿主模型关联附件查询
CREATE INDEX idx_media_collection ON media (collection_name); -- 媒体集合归类检索索引

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. 通用站内消息通知表 (notifications，基于 UUIDv7)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE notifications (
  id uuid NOT NULL DEFAULT uuidv7(), -- UUIDv7 主键标识符（默认自动生成）
  notifiable_type varchar(255) NOT NULL, -- 接收主体类型（如 App\Models\User, user）
  notifiable_id varchar(255) NOT NULL, -- 接收主体 ID
  type varchar(255) NOT NULL, -- 业务通知类别标识（如 App\Notifications\InvoicePaid, invoice.paid）
  data text NOT NULL, -- 结构化通知消息体数据（JSON 文本序列化）
  read_at timestamptz NULL, -- 用户阅读时间戳（为空表示未读）
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 记录创建时间戳
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 记录最后更新时间戳
  deleted_at timestamptz NULL, -- 软删除时间戳
  PRIMARY KEY (id)
);

-- 消息通知检索索引
CREATE INDEX idx_notifiable ON notifications (notifiable_type, notifiable_id); -- 接收主体复合检索索引
CREATE INDEX idx_notifications_read_at ON notifications (read_at); -- 已读/未读状态过滤索引
CREATE INDEX idx_notifications_deleted_at ON notifications (deleted_at); -- 软删除过滤索引
